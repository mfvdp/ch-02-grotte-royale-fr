    // Marque pour rejouer après la fin de la partie. L'écran de fin la pose juste avant control.reset(). Au démarrage
    // suivant, le jeu la lit, l'efface aussitôt et va directement à l'image du titre, sans l'intro. Quand on éteint
    // puis rallume la console, la marque a disparu : l'intro se joue alors de nouveau.
    export const marqueRejouer = "neustart-titel"
    // Vrai quand ce démarrage est un nouveau départ après la fin de la partie.
    export let versTitreDirect = false
    export function texte(idTexte: IdTexte): string {
        return textes[idTexte]
    }
    export function formater(idTexte: IdTexte, premier: number, second: number = 0): string {
        let s = texte(idTexte)
        let i = s.indexOf("{0}")
        if (i >= 0) s = s.substr(0, i) + premier + s.substr(i + 3)
        i = s.indexOf("{1}")
        if (i >= 0) s = s.substr(0, i) + second + s.substr(i + 3)
        return s
    }
    // Au démarrage : si la marqueRejouer est posée, le jeu va tout de suite à l'image du titre. La marque ne vaut que
    // pour ce seul démarrage et elle est effacée aussitôt. Ensuite, on ajoute les menus.
    export function initialiser(): void {
        versTitreDirect = settings.exists(marqueRejouer)
        if (versTitreDirect) settings.remove(marqueRejouer)
        pause(100)
        installerMenus()
    }
